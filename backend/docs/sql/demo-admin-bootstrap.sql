/*
  First-admin bootstrap for the isolated recovery demo database only.

  Prepare @AdminPasswordHash from an owner-chosen password using the application's
  BCryptPasswordEncoder (PasswordConfig). Never put a plaintext password here.
  This script inserts one fictional ADMIN only; it never changes an existing user.
  After bootstrap, create the remaining accounts and catalog through authorized APIs.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @ExpectedServer sysname = N'sportcenter-recovery-sql';
DECLARE @ExpectedDatabase sysname = N'SportCenterDB';
DECLARE @ActualServer sysname = CONVERT(sysname, SERVERPROPERTY('ServerName'));
DECLARE @AdminName nvarchar(200) = N'Demo Administrator';
DECLARE @AdminEmail varchar(150) = 'demo.admin@sportcenter.test';
DECLARE @AdminPasswordHash varchar(255) = '';
DECLARE @AdminDateOfBirth date = '1985-03-14';

IF @ActualServer IS NULL OR @ActualServer <> @ExpectedServer
    THROW 50501, 'Admin bootstrap stopped: unexpected SQL Server identity.', 1;
IF DB_NAME() <> @ExpectedDatabase
    THROW 50502, 'Admin bootstrap stopped: unexpected database.', 1;
IF @@TRANCOUNT <> 0
    THROW 50503, 'Run the admin bootstrap without an existing transaction.', 1;
IF OBJECT_ID(N'dbo.users', N'U') IS NULL
    THROW 50504, 'Admin bootstrap stopped: dbo.users is missing.', 1;
IF COL_LENGTH(N'dbo.users', N'name') IS NULL
   OR COL_LENGTH(N'dbo.users', N'email') IS NULL
   OR COL_LENGTH(N'dbo.users', N'date_of_birth') IS NULL
   OR COL_LENGTH(N'dbo.users', N'password_hash') IS NULL
   OR COL_LENGTH(N'dbo.users', N'role') IS NULL
   OR COL_LENGTH(N'dbo.users', N'status') IS NULL
   OR COL_LENGTH(N'dbo.users', N'created_at') IS NULL
    THROW 50505, 'Admin bootstrap stopped: dbo.users does not match the reviewed release schema.', 1;
IF LEN(@AdminPasswordHash) <> 60
   OR LEFT(@AdminPasswordHash, 4) NOT IN ('$2a$', '$2b$', '$2y$')
    THROW 50506, 'Supply a 60-character BCrypt hash generated by the application password encoder.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @LockResult int;
    EXEC @LockResult = sys.sp_getapplock
        @Resource = N'SportCenter.RecoveryDemo.AdminBootstrap',
        @LockMode = 'Exclusive',
        @LockOwner = 'Transaction',
        @LockTimeout = 10000;
    IF @LockResult < 0
        THROW 50507, 'Admin bootstrap could not acquire its transaction lock.', 1;

    IF EXISTS (
        SELECT 1
        FROM dbo.users WITH (UPDLOCK, HOLDLOCK)
        WHERE LOWER(email) = LOWER(@AdminEmail)
          AND (name <> @AdminName OR date_of_birth IS NULL OR date_of_birth <> @AdminDateOfBirth
               OR role <> 'ADMIN' OR status <> 'ACTIVE')
    )
        THROW 50508, 'The demo admin email already belongs to a different or inactive account; no account was changed.', 1;

    IF NOT EXISTS (
        SELECT 1 FROM dbo.users WITH (UPDLOCK, HOLDLOCK)
        WHERE LOWER(email) = LOWER(@AdminEmail)
    )
    BEGIN
        INSERT dbo.users (name, email, date_of_birth, password_hash, role, status, created_at)
        OUTPUT inserted.id AS admin_user_id
        VALUES (@AdminName, @AdminEmail, @AdminDateOfBirth, @AdminPasswordHash,
                'ADMIN', 'ACTIVE', SYSDATETIME());
    END
    ELSE
    BEGIN
        PRINT 'Matching demo ADMIN already exists; it was left unchanged.';
    END;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
